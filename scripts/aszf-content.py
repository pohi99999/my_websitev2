# Writes app/aszf/content.ts from the approved ÁSZF markdown files, word for word (Marveen 5829, Péter's
# approval: Telegram 12456). The text is not edited here or in the page: only the page decides how it
# looks. Each language's sha256 goes next to its text, so a test can tell that the published text is
# the approved one.
#
#   ASZF_WITH_TRANSLATIONS=1 python3 scripts/aszf-content.py <dir> [suffix]
#   reads ASZF-VEGLEGES-HU<suffix>.md, ASZF-EN<suffix>.md, ASZF-DE<suffix>.md (without the variable only the
#   Hungarian text). The suffix picks the dated copies (e.g. -20261101: the approved files with only the
#   effective-date line filled in, Peter GO 12491); the approved files themselves are never rewritten.
import hashlib, json, os, sys

src = sys.argv[1]
suffix = sys.argv[2] if len(sys.argv) > 2 else ''
files = {'hu': f'ASZF-VEGLEGES-HU{suffix}.md', 'en': f'ASZF-EN{suffix}.md', 'de': f'ASZF-DE{suffix}.md'}
langs = {}
for lang, name in files.items():
    path = os.path.join(src, name)
    if os.path.exists(path) and (lang == 'hu' or os.environ.get('ASZF_WITH_TRANSLATIONS') == '1'):
        text = open(path, encoding='utf-8').read()
        langs[lang] = (text, hashlib.sha256(text.encode('utf-8')).hexdigest(), name)

out = [
    '// Generated by scripts/aszf-content.py from the approved ÁSZF markdown (Marveen 5829, Telegram 12456).',
    '// Do not edit by hand: change the source and regenerate. The sha256 is of the text as approved.',
    '',
    "export type AszfLang = 'hu' | 'en' | 'de';",
    '',
    'export const ASZF: Partial<Record<AszfLang, { source: string; sha256: string; markdown: string }>> = {',
]
for lang, (text, sha, name) in langs.items():
    out.append(f'  {lang}: {{')
    out.append(f'    source: {json.dumps(name)},')
    out.append(f'    sha256: {json.dumps(sha)},')
    out.append(f'    markdown: {json.dumps(text, ensure_ascii=False)},')
    out.append('  },')
out.append('};')
open('app/aszf/content.ts', 'w', encoding='utf-8').write('\n'.join(out) + '\n')
for lang, (_, sha, name) in langs.items():
    print(lang, name, sha)
